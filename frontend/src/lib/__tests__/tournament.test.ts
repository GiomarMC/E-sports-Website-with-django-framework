import { describe, expect, it } from 'vitest'
import {
  BOX_W,
  currentTournament,
  GAP_X,
  groupByDay,
  isPowerOfTwo,
  layoutBracket,
  layoutDoubleBracket,
  registrationTotal,
  roundLabel,
} from '../tournament'
import type { Match, Tournament } from '../types'

function match(id: number, round: number, position: number, next: number | null = null): Match {
  return {
    id,
    tournament: 1,
    game: 1,
    stage: 1,
    stage_name: 'Playoffs',
    group: null,
    group_name: null,
    bracket: '',
    round,
    position,
    label: '',
    scheduled_at: null,
    best_of: 1,
    status: 'scheduled',
    is_bye: false,
    winner: null,
    next_match: next,
    next_match_slot: next ? 1 : null,
    loser_next_match: null,
    loser_next_match_slot: null,
    notes: '',
    can_draw: false,
    participants: [],
    streams: [],
    updated_at: '',
  }
}

describe('registrationTotal', () => {
  it('multiplies the fee per player by the number of players', () => {
    expect(registrationTotal('5.00', 6)).toBe(30)
    expect(registrationTotal('2.50', 3)).toBe(7.5)
  })
})

describe('isPowerOfTwo', () => {
  it('accepts only bracket sizes without byes', () => {
    expect([1, 2, 3, 4, 6, 8, 10, 12, 16, 32].filter(isPowerOfTwo)).toEqual([2, 4, 8, 16, 32])
  })
})

describe('roundLabel', () => {
  it('translates the labels generated by the API', () => {
    expect(roundLabel('Final', 3)).toBe('Final')
    expect(roundLabel('Semifinal', 2)).toBe('Semifinales')
    expect(roundLabel('Round of 16', 1)).toBe('Ronda de 16')
    expect(roundLabel('', 4)).toBe('Ronda 4')
    expect(roundLabel('Gran final', 4)).toBe('Gran final')
    expect(roundLabel('Lower Round 3', 3)).toBe('Ronda 3 del lower')
    expect(roundLabel('Upper Final', 3)).toBe('Final del upper')
    expect(roundLabel('Grand Final', 1)).toBe('Gran final')
  })
})

describe('layoutBracket', () => {
  it('centers each match between the matches that feed it', () => {
    const final = match(7, 3, 1)
    const semis = [match(5, 2, 1, 7), match(6, 2, 2, 7)]
    const quarters = [match(1, 1, 1, 5), match(2, 1, 2, 5), match(3, 1, 3, 6), match(4, 1, 4, 6)]
    const { items, lines } = layoutBracket([
      { round: 1, matches: quarters },
      { round: 2, matches: semis },
      { round: 3, matches: [final] },
    ])
    const y = (id: number) => items.find((item) => item.match.id === id)!.y
    expect(y(5)).toBe((y(1) + y(2)) / 2)
    expect(y(6)).toBe((y(3) + y(4)) / 2)
    expect(y(7)).toBe((y(5) + y(6)) / 2)
    expect(lines).toHaveLength(6)
  })

  it('stacks matches without feeders below the previous one', () => {
    const { items } = layoutBracket([
      { round: 1, matches: [match(1, 1, 1), match(2, 1, 2)] },
      { round: 2, matches: [match(3, 2, 1), match(4, 2, 2)] },
    ])
    const ys = items.filter((i) => i.match.round === 2).map((i) => i.y)
    expect(ys[0]).toBe(0)
    expect(ys[1]).toBeGreaterThan(ys[0])
  })
})

describe('layoutDoubleBracket', () => {
  it('draws upper, lower and grand final as one bracket', () => {
    // 4 teams: the semifinal losers meet in the lower bracket.
    const side = (m: Match, bracket: Match['bracket'], loser: number | null = null) => ({ ...m, bracket, loser_next_match: loser })
    const sections = [
      { group: null, bracket: 'upper' as const, rounds: [
        { round: 1, matches: [side(match(1, 1, 1, 3), 'upper', 4), side(match(2, 1, 2, 3), 'upper', 4)] },
        { round: 2, matches: [side(match(3, 2, 1, 6), 'upper', 5)] },
      ] },
      { group: null, bracket: 'lower' as const, rounds: [
        { round: 1, matches: [side(match(4, 1, 1, 5), 'lower')] },
        { round: 2, matches: [side(match(5, 2, 1, 6), 'lower')] },
      ] },
      { group: null, bracket: 'final' as const, rounds: [{ round: 1, matches: [side(match(6, 1, 1), 'final')] }] },
    ]
    const { items, lines, headers } = layoutDoubleBracket(sections)
    const at = (id: number) => items.find((item) => item.match.id === id)!
    const column = (id: number) => at(id).x / (BOX_W + GAP_X)
    expect([1, 2, 3, 4, 5, 6].map(column)).toEqual([0, 0, 1, 0, 1, 2])
    expect(at(4).y).toBeGreaterThan(at(2).y)
    expect(at(6).y).toBe((at(3).y + at(5).y) / 2)
    expect(lines.map((line) => line.id).sort()).toEqual([1, 2, 3, 4, 5])
    expect(headers).toHaveLength(5)
  })
})

describe('layoutDoubleBracket with 8 teams', () => {
  it('lines up the upper final with the lower final', () => {
    const m = (id: number, round: number, position: number, bracket: Match['bracket'], next: number | null, loser: number | null = null) => ({
      ...match(id, round, position, next),
      bracket,
      loser_next_match: loser,
    })
    const sections = [
      { group: null, bracket: 'upper' as const, rounds: [
        { round: 1, matches: [m(1, 1, 1, 'upper', 5, 8), m(2, 1, 2, 'upper', 5, 8), m(3, 1, 3, 'upper', 6, 9), m(4, 1, 4, 'upper', 6, 9)] },
        { round: 2, matches: [m(5, 2, 1, 'upper', 7, 10), m(6, 2, 2, 'upper', 7, 11)] },
        { round: 3, matches: [m(7, 3, 1, 'upper', 14, 13)] },
      ] },
      { group: null, bracket: 'lower' as const, rounds: [
        { round: 1, matches: [m(8, 1, 1, 'lower', 10), m(9, 1, 2, 'lower', 11)] },
        { round: 2, matches: [m(10, 2, 1, 'lower', 12), m(11, 2, 2, 'lower', 12)] },
        { round: 3, matches: [m(12, 3, 1, 'lower', 13)] },
        { round: 4, matches: [m(13, 4, 1, 'lower', 14)] },
      ] },
      { group: null, bracket: 'final' as const, rounds: [{ round: 1, matches: [m(14, 1, 1, 'final', null)] }] },
    ]
    const { items } = layoutDoubleBracket(sections)
    const column = (id: number) => items.find((item) => item.match.id === id)!.x / (BOX_W + GAP_X)
    expect([1, 5, 7].map(column)).toEqual([0, 1, 3])
    expect([8, 10, 12, 13].map(column)).toEqual([0, 1, 2, 3])
    expect(column(14)).toBe(4)
  })
})

describe('currentTournament', () => {
  const base = { game: 1, start_date: '2026-11-01T00:00:00Z' } as Tournament
  it('prefers the ongoing tournament, then the next upcoming one', () => {
    const list = [
      { ...base, id: 1, status: 'completed' },
      { ...base, id: 2, status: 'upcoming', start_date: '2026-12-01T00:00:00Z' },
      { ...base, id: 3, status: 'upcoming', start_date: '2026-11-15T00:00:00Z' },
    ] as Tournament[]
    expect(currentTournament(list, 1)?.id).toBe(3)
    expect(currentTournament([...list, { ...base, id: 4, status: 'ongoing' } as Tournament], 1)?.id).toBe(4)
    expect(currentTournament(list, 2)).toBeUndefined()
  })
})

describe('groupByDay', () => {
  it('groups matches by local day and keeps unscheduled apart', () => {
    const a = { ...match(1, 1, 1), scheduled_at: '2026-11-20T15:00:00' }
    const b = { ...match(2, 1, 2), scheduled_at: '2026-11-20T18:00:00' }
    const c = match(3, 1, 3)
    const days = groupByDay([a, b, c])
    expect(days).toHaveLength(2)
    expect(days[0][1]).toHaveLength(2)
    expect(days[1][0]).toBe('none')
  })
})
